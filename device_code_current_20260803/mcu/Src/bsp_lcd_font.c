const uint8_t *BSP_LCD_Font_Get5x7(char ch)
{
    /* 为了节省 Flash，当前没有单独存小写字母，统一转成大写显示。 */
    if ((ch >= 'a') && (ch <= 'z')) {
        ch = (char)(ch - 'a' + 'A');
    }
    /* 未收录的字符用空格代替，避免访问数组越界。 */
    if ((ch < (char)BSP_FONT_ASCII_FIRST) || (ch > (char)BSP_FONT_ASCII_LAST)) {
        ch = ' ';
    }

    return g_ascii_5x7[(uint8_t)ch - BSP_FONT_ASCII_FIRST];
}
